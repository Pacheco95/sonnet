#!/usr/bin/env python3
"""Cuts the icons the editor draws out of the Lucide icon font and embeds them (docs/editor.md, "Icons").

  python3 tools/generate_lucide_font.py path/to/lucide.ttf

`lucide.ttf` is font/lucide.ttf of the `lucide-static` npm package (checked at 1.59.0). The icons used are
the ones in ICONS, by name; the script finds each name's codepoint in the font's glyph names, keeps only those
glyphs, and writes modules/editor/src/LucideFontData.cpp. modules/editor/include/sonnet/editor/Icons.h names the same
codepoints, and the editor tests check that every name there is in the embedded font. Needs fontTools.
The output is committed; re-running with the same font overwrites it identically. The licences travel with the
font in THIRD_PARTY_NOTICES.md.
"""
import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "modules/editor/src/LucideFontData.cpp"

# Lucide icon names, in the order of the codepoints in Icons.h.
ICONS = [
    "folder", "file", "image", "globe", "palette", "box", "package", "blocks", "file-code", "volume-2",
    "type", "play", "bone", "film", "layout-grid", "list",
]


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    font = TTFont(sys.argv[1])
    names = {glyph: code for code, glyph in font.getBestCmap().items()}
    missing = [icon for icon in ICONS if icon not in names]
    if missing:
        print(f"not in the font: {', '.join(missing)}")
        return 1
    codepoints = sorted(names[icon] for icon in ICONS)
    options = subset.Options()
    options.layout_features = []
    options.name_IDs = [1, 2]
    options.notdef_outline = True
    options.glyph_names = False
    options.hinting = False
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=codepoints)
    subsetter.subset(font)
    from io import BytesIO
    buffer = BytesIO()
    font.save(buffer)
    data = buffer.getvalue()

    lines = ["// Generated by tools/generate_lucide_font.py from the Lucide icon font; do not edit.",
             "// Lucide is ISC licensed, its Feather-derived icons MIT: see THIRD_PARTY_NOTICES.md.",
             '#include <sonnet/editor/Icons.h>', "", "namespace sonnet::editor {", "", "// clang-format off",
             "const unsigned char LucideFontData[] = {"]
    for start in range(0, len(data), 24):
        lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in data[start:start + 24]) + ",")
    lines += ["};", "// clang-format on", f"const unsigned int LucideFontSize = {len(data)};", "",
              "} // namespace sonnet::editor", ""]
    OUTPUT.write_text("\n".join(lines))
    print(f"{len(codepoints)} glyphs, {len(data)} bytes -> {OUTPUT.relative_to(ROOT)}")
    for icon in ICONS:
        print(f"  {icon}: U+{names[icon]:04X}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
