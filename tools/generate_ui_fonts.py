#!/usr/bin/env python3
"""Cuts the editor's text fonts out of Google Fonts' variable TTFs and embeds them (docs/editor.md, "Fonts").

  python3 tools/generate_ui_fonts.py inter path/to/Inter[opsz,wght].ttf

`inter` is the font to cut, a key of FONTS; the file is its variable TTF from github.com/google/fonts (ofl/inter,
checked at Inter 4.001). ImGui's stb_truetype reads only a font's default instance and cannot pick an axis, so the
script pins the axes to a static instance first, keeps the glyphs of the ranges below, and writes
modules/editor/src/<Name>FontData.cpp. The output is committed; re-running with the same font overwrites it
identically. The licences travel with the fonts in THIRD_PARTY_NOTICES.md. Needs fontTools.
"""
import sys
from io import BytesIO
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parent.parent

# Basic Latin, Latin-1 and Latin Extended-A (names and log lines may carry any Western European text), the general
# punctuation a label uses, and the degree sign.
LATIN = (
    list(range(0x20, 0x7F))
    + list(range(0xA0, 0x180))
    + [0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026]
)

# key -> (symbol prefix, the instance's axes, the font's name for the generated comment, its licence line)
FONTS = {
    "inter": ("Inter", {"wght": 400, "opsz": 14}, "Inter", "Inter is SIL OFL 1.1 licensed"),
}


def main() -> int:
    if len(sys.argv) != 3 or sys.argv[1] not in FONTS:
        print(__doc__)
        return 2
    prefix, axes, name, licence = FONTS[sys.argv[1]]
    font = instancer.instantiateVariableFont(TTFont(sys.argv[2]), axes)
    options = subset.Options()
    options.layout_features = []
    options.name_IDs = [0, 1, 2, 13, 14]  # the copyright and licence names travel with the font
    options.notdef_outline = True
    options.glyph_names = False
    options.hinting = False
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=LATIN)
    subsetter.subset(font)
    buffer = BytesIO()
    font.save(buffer)
    data = buffer.getvalue()

    output = ROOT / f"modules/editor/src/{prefix}FontData.cpp"
    lines = [f"// Generated by tools/generate_ui_fonts.py from the {name} variable font; do not edit.",
             f"// {licence}: see THIRD_PARTY_NOTICES.md.",
             "#include <sonnet/editor/Fonts.h>", "", "namespace sonnet::editor {", "", "// clang-format off",
             f"const unsigned char {prefix}FontData[] = {{"]
    for start in range(0, len(data), 24):
        lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in data[start:start + 24]) + ",")
    lines += ["};", "// clang-format on", f"const unsigned int {prefix}FontSize = {len(data)};", "",
              "} // namespace sonnet::editor", ""]
    output.write_text("\n".join(lines))
    print(f"{len(font.getBestCmap())} glyphs, {len(data)} bytes -> {output.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
